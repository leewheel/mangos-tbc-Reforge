static const size_t g_opcodeMapSize = sizeof(g_opcodeMap) / sizeof(g_opcodeMap[0]);

// 现代(2.5.3) opcode → 旧版(2.4.3/mangos) opcode；找不到返回 -1
inline int ModernToLegacyOpcode(uint16 modernOpcode)
{
    // 二分查找（表按 modernOpcode 升序）
    size_t lo = 0, hi = g_opcodeMapSize;
    while (lo < hi)
    {
        size_t mid = (lo + hi) / 2;
        if (g_opcodeMap[mid].modernOpcode < modernOpcode)
            lo = mid + 1;
        else
            hi = mid;
    }
    if (lo < g_opcodeMapSize && g_opcodeMap[lo].modernOpcode == modernOpcode)
        return g_opcodeMap[lo].legacyOpcode;
    return -1;
}

// 旧版(2.4.3/mangos) opcode → 现代(2.5.3) opcode；找不到返回 -1
inline int LegacyToModernOpcode(uint16 legacyOpcode)
{
    // 线性查找（发送路径频率相对低，表规模小）
    for (size_t i = 0; i < g_opcodeMapSize; ++i)
        if (g_opcodeMap[i].legacyOpcode == legacyOpcode)
            return g_opcodeMap[i].modernOpcode;
    return -1;
}
